-- =====================================================
--  💰 Presupuestos: instalación (cableado, cámaras, WiFi), desmontaje / desocupar WH u oficina,
--  mudanza, reparación de PC/impresoras, diseño web, desarrollo de software, soporte mensual (MSP) y libre.
--  Horas hombre, personas, semanas, precio por hora y por punto, materiales, equipos y cargos mensuales.
--  El tipo de trabajo se guarda dentro de datos (datos->>'tipo'); no hace falta otra tabla.
--  Aprende de las horas reales de cada trabajo cerrado.
--  Supabase > SQL Editor > New query > pega todo > Run
--  Requiere supabase-roles.sql (y supabase-diseno.sql para el plano). Se puede correr más de una vez. No borra nada.
--  Solo el Super admin y los operadores ven los presupuestos (los usuarios "cliente" NO).
-- =====================================================

create or replace function public.es_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from perfiles where user_id = auth.uid() and rol in ('admin', 'operador'))
$$;
revoke all on function public.es_staff() from public, anon;
grant execute on function public.es_staff() to authenticated;

-- 1) Presupuestos
create table if not exists public.presupuestos (
  id           uuid primary key default gen_random_uuid(),
  numero       integer generated by default as identity,
  cliente      text not null,                  -- cliente del inventario o nombre del prospecto
  prospecto    boolean not null default false,
  titulo       text,
  estado       text not null default 'borrador',   -- borrador | enviado | aprobado | perdido | completado
  datos        jsonb not null default '{}'::jsonb, -- sitio, cantidades, equipos, materiales, precios
  totales      jsonb not null default '{}'::jsonb, -- foto del cálculo (horas, días, personas, precios)
  horas_est    numeric,
  horas_real   numeric,                        -- se llena al cerrar el trabajo (para aprender)
  cierre       jsonb not null default '{}'::jsonb,
  creado_por   text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists presupuestos_fecha_idx on public.presupuestos (created_at desc);
alter table public.presupuestos enable row level security;

-- 2) Configuración: tarifas, tiempos por tarea, factores, materiales y lista de precios de equipos
create table if not exists public.presu_config (
  id         integer primary key default 1 check (id = 1),
  datos      jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
insert into public.presu_config (id) values (1) on conflict (id) do nothing;
alter table public.presu_config enable row level security;

do $$
declare pol record;
begin
  for pol in select policyname, tablename from pg_policies where schemaname = 'public' and tablename in ('presupuestos', 'presu_config') loop
    execute format('drop policy %I on public.%I', pol.policyname, pol.tablename);
  end loop;
  execute 'create policy presu_ver    on public.presupuestos for select to authenticated using (es_staff())';
  execute 'create policy presu_crear  on public.presupuestos for insert to authenticated with check (es_staff())';
  execute 'create policy presu_editar on public.presupuestos for update to authenticated using (es_staff()) with check (es_staff())';
  execute 'create policy presu_borrar on public.presupuestos for delete to authenticated using (es_admin())';
  execute 'create policy pconf_ver    on public.presu_config for select to authenticated using (es_staff())';
  execute 'create policy pconf_editar on public.presu_config for update to authenticated using (es_admin()) with check (es_admin())';
  execute 'revoke all on public.presupuestos, public.presu_config from anon';
  execute 'grant select, insert, update, delete on public.presupuestos to authenticated';
  execute 'grant select, update on public.presu_config to authenticated';
end $$;

create or replace function public.presu_fecha()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.updated_at := now();
  if tg_op = 'INSERT' then new.creado_por := coalesce(nullif(split_part(coalesce(auth.jwt() ->> 'email', ''), '@', 1), ''), new.creado_por); end if;
  return new;
end $$;
drop trigger if exists presu_fecha on public.presupuestos;
create trigger presu_fecha before insert or update on public.presupuestos for each row execute function public.presu_fecha();
create or replace function public.presu_conf_fecha()
returns trigger language plpgsql as $$ begin new.updated_at := now(); return new; end $$;
drop trigger if exists presu_conf_fecha on public.presu_config;
create trigger presu_conf_fecha before update on public.presu_config for each row execute function public.presu_conf_fecha();

