-- =====================================================
--  🛠 Trabajos en proceso: avance (%), fases, línea de tiempo, diario de obra,
--  retrasos (nuestros / del cliente / otros), lo que falta (material, herramientas, equipos)
--  la lista de materiales para la puesta en marcha y los comentarios sobre las notas del día.
--  Supabase > SQL Editor > New query > pega todo > Run
--  Requiere supabase-roles.sql. Se puede correr más de una vez. No borra nada.
--  Solo el Super admin y los operadores lo ven (los usuarios "cliente" NO).
-- =====================================================

create or replace function public.es_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from perfiles where user_id = auth.uid() and rol in ('admin', 'operador'))
$$;
revoke all on function public.es_staff() from public, anon;
grant execute on function public.es_staff() to authenticated;

-- 1) Trabajos
create table if not exists public.trabajos (
  id              uuid primary key default gen_random_uuid(),
  numero          integer generated by default as identity,
  cliente         text not null,
  titulo          text not null,
  direccion       text,
  estado          text not null default 'pendiente' check (estado in ('pendiente', 'en_proceso', 'pausado', 'terminado', 'cancelado')),
  progreso        integer not null default 0 check (progreso between 0 and 100),
  auto_fases      boolean not null default false,       -- el % sale de las fases
  fases           jsonb not null default '[]'::jsonb,   -- [{"n":"Cableado","peso":40,"pct":60}]
  fecha_inicio    date,
  fecha_fin_est   date,                                 -- fecha de entrega prometida
  fecha_fin_real  date,
  responsable     text,
  equipo          text,                                 -- técnicos asignados
  presupuesto_id  uuid,                                 -- de qué presupuesto salió (opcional)
  notas           text,
  creado_por      text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists trabajos_estado_idx on public.trabajos (estado, fecha_fin_est);
-- materiales para la puesta en marcha (v9.2): [{"d":"Cable Cat6","cant":2000,"uni":"ft","sid":"<id del stock>","sac":0,"ok":false}]
alter table public.trabajos add column if not exists materiales jsonb not null default '[]'::jsonb;
alter table public.trabajos enable row level security;

-- 2) Diario de obra (una nota por día / visita)
create table if not exists public.trabajo_diario (
  id            uuid primary key default gen_random_uuid(),
  trabajo_id    uuid not null references public.trabajos(id) on delete cascade,
  fecha         date not null default current_date,
  personas      integer,
  horas         numeric,                 -- horas trabajadas (total del equipo)
  avance        integer check (avance between 0 and 100),   -- % del trabajo al final del día
  hecho         text,                    -- qué se hizo
  dificultades  text,                    -- trabas / problemas
  no_logrado    text,                    -- qué no se pudo terminar y por qué
  retraso_horas numeric,                 -- horas perdidas
  retraso_causa text check (retraso_causa in ('nuestro', 'cliente', 'proveedor', 'clima', 'permiso', 'otro')),
  retraso_motivo text,
  autor         text,
  created_at    timestamptz not null default now()
);
create index if not exists trabajo_diario_idx on public.trabajo_diario (trabajo_id, fecha desc);
alter table public.trabajo_diario enable row level security;

-- 3) Lo que falta para el trabajo
create table if not exists public.trabajo_faltantes (
  id            uuid primary key default gen_random_uuid(),
  trabajo_id    uuid not null references public.trabajos(id) on delete cascade,
  tipo          text not null default 'material' check (tipo in ('material', 'herramienta', 'equipo', 'otro')),
  descripcion   text not null,
  cantidad      numeric,
  unidad        text,
  urgente       boolean not null default false,
  estado        text not null default 'pendiente' check (estado in ('pendiente', 'pedido', 'en_camino', 'recibido', 'resuelto')),
  stock_item_id uuid,                    -- si es un producto del stock de la oficina
  nota          text,
  autor         text,
  created_at    timestamptz not null default now(),
  resuelto_at   timestamptz
);
create index if not exists trabajo_faltantes_idx on public.trabajo_faltantes (trabajo_id, estado);
alter table public.trabajo_faltantes enable row level security;

do $$
declare pol record;
begin
  for pol in select policyname, tablename from pg_policies where schemaname = 'public' and tablename in ('trabajos', 'trabajo_diario', 'trabajo_faltantes') loop
    execute format('drop policy %I on public.%I', pol.policyname, pol.tablename);
  end loop;
  execute 'create policy trb_ver    on public.trabajos for select to authenticated using (es_staff())';
  execute 'create policy trb_crear  on public.trabajos for insert to authenticated with check (es_staff())';
  execute 'create policy trb_editar on public.trabajos for update to authenticated using (es_staff()) with check (es_staff())';
  execute 'create policy trb_borrar on public.trabajos for delete to authenticated using (es_admin())';
  execute 'create policy trd_ver    on public.trabajo_diario for select to authenticated using (es_staff())';
  execute 'create policy trd_crear  on public.trabajo_diario for insert to authenticated with check (es_staff())';
  execute 'create policy trd_editar on public.trabajo_diario for update to authenticated using (es_admin()) with check (es_admin())';   -- corregir notas: solo administradores (v9.5.3)
  execute 'create policy trd_borrar on public.trabajo_diario for delete to authenticated using (es_admin())';
  execute 'create policy trf_ver    on public.trabajo_faltantes for select to authenticated using (es_staff())';
  execute 'create policy trf_crear  on public.trabajo_faltantes for insert to authenticated with check (es_staff())';
  execute 'create policy trf_editar on public.trabajo_faltantes for update to authenticated using (es_staff()) with check (es_staff())';
  execute 'create policy trf_borrar on public.trabajo_faltantes for delete to authenticated using (es_staff())';
  execute 'revoke all on public.trabajos, public.trabajo_diario, public.trabajo_faltantes from anon';
  execute 'grant select, insert, update, delete on public.trabajos, public.trabajo_diario, public.trabajo_faltantes to authenticated';
end $$;

-- fecha de cambio y autor automáticos
create or replace function public.trb_fecha()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.updated_at := now();
  if tg_op = 'INSERT' then new.creado_por := coalesce(nullif(split_part(coalesce(auth.jwt() ->> 'email', ''), '@', 1), ''), new.creado_por); end if;
  return new;
end $$;
drop trigger if exists trb_fecha on public.trabajos;
create trigger trb_fecha before insert or update on public.trabajos for each row execute function public.trb_fecha();

create or replace function public.trb_autor()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.autor := coalesce(nullif(split_part(coalesce(auth.jwt() ->> 'email', ''), '@', 1), ''), new.autor);
  return new;
end $$;
drop trigger if exists trd_autor on public.trabajo_diario;
create trigger trd_autor before insert on public.trabajo_diario for each row execute function public.trb_autor();
drop trigger if exists trf_autor on public.trabajo_faltantes;
create trigger trf_autor before insert on public.trabajo_faltantes for each row execute function public.trb_autor();

-- 4) Comentarios sobre las notas del día (v9.6): cualquier usuario del equipo comenta el resumen ya hecho
create table if not exists public.trabajo_coment (
  id          uuid primary key default gen_random_uuid(),
  diario_id   uuid not null references public.trabajo_diario(id) on delete cascade,
  trabajo_id  uuid not null references public.trabajos(id) on delete cascade,
  texto       text not null check (length(trim(texto)) > 0),
  autor       text,
  autor_id    uuid default auth.uid(),
  created_at  timestamptz not null default now()
);
create index if not exists trabajo_coment_idx on public.trabajo_coment (diario_id, created_at);
alter table public.trabajo_coment enable row level security;
do $$
declare pol record;
begin
  for pol in select policyname from pg_policies where schemaname = 'public' and tablename = 'trabajo_coment' loop
    execute format('drop policy %I on public.trabajo_coment', pol.policyname);
  end loop;
  execute 'create policy trc_ver    on public.trabajo_coment for select to authenticated using (es_staff())';
  execute 'create policy trc_crear  on public.trabajo_coment for insert to authenticated with check (es_staff() and autor_id = auth.uid())';
  -- borrar: el que lo escribió o un administrador
  execute 'create policy trc_borrar on public.trabajo_coment for delete to authenticated using (es_admin() or autor_id = auth.uid())';
  execute 'revoke all on public.trabajo_coment from anon';
  execute 'grant select, insert, delete on public.trabajo_coment to authenticated';
end $$;
drop trigger if exists trc_autor on public.trabajo_coment;
create trigger trc_autor before insert on public.trabajo_coment for each row execute function public.trb_autor();

